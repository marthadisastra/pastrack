CREATE TABLE IF NOT EXISTS sensor_calibration_sessions (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 sensor_id BIGINT UNSIGNED NOT NULL,
 fuel_sensor_id BIGINT UNSIGNED NOT NULL,
 device_id BIGINT UNSIGNED NOT NULL,
 vehicle_id BIGINT UNSIGNED NOT NULL,
 quantity VARCHAR(32) NOT NULL,
 capacity_l DECIMAL(12,3) NOT NULL,
 state VARCHAR(24) NOT NULL,
 started_by BIGINT UNSIGNED NOT NULL,
 started_at DATETIME(3) NOT NULL,
 phase_started_at DATETIME(3) NOT NULL,
 phase_telemetry_id BIGINT UNSIGNED NOT NULL,
 empty_raw DECIMAL(14,3) NULL,
 empty_telemetry_id BIGINT UNSIGNED NULL,
 empty_evidence JSON NULL,
 full_raw DECIMAL(14,3) NULL,
 full_telemetry_id BIGINT UNSIGNED NULL,
 calibration_id BIGINT UNSIGNED NULL,
 error_message VARCHAR(255) NULL,
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
 INDEX ix_sensor_calibration_session (sensor_id,id),
 CONSTRAINT fk_calibration_session_sensor FOREIGN KEY(sensor_id) REFERENCES ble_sensors(id),
 CONSTRAINT fk_calibration_session_fuel FOREIGN KEY(fuel_sensor_id) REFERENCES fuel_sensors(id),
 CONSTRAINT fk_calibration_session_gps FOREIGN KEY(device_id) REFERENCES gps_devices(id),
 CONSTRAINT fk_calibration_session_vehicle FOREIGN KEY(vehicle_id) REFERENCES vehicles(id),
 CONSTRAINT fk_calibration_session_user FOREIGN KEY(started_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
