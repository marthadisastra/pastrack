CREATE TABLE IF NOT EXISTS maintenance_work_orders (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  vehicle_id BIGINT UNSIGNED NOT NULL,
  scope VARCHAR(64) NOT NULL,
  title VARCHAR(120) NOT NULL,
  description VARCHAR(500) NULL,
  trigger_value DECIMAL(14,2) NOT NULL,
  trigger_unit VARCHAR(8) NOT NULL,
  current_value DECIMAL(14,2) NOT NULL DEFAULT 0,
  facility VARCHAR(160) NOT NULL,
  bay VARCHAR(80) NOT NULL DEFAULT 'Pending allocation',
  budget DECIMAL(14,2) NOT NULL DEFAULT 0,
  scheduled_date DATE NOT NULL,
  priority VARCHAR(16) NOT NULL DEFAULT 'Normal',
  status VARCHAR(24) NOT NULL DEFAULT 'Scheduled',
  row_version BIGINT UNSIGNED NOT NULL DEFAULT 1,
  created_by BIGINT UNSIGNED NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY ix_maintenance_vehicle_status (vehicle_id,status),
  KEY ix_maintenance_date (scheduled_date),
  CONSTRAINT fk_maintenance_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles(id),
  CONSTRAINT fk_maintenance_user FOREIGN KEY (created_by) REFERENCES users(id)
);
