CREATE TABLE IF NOT EXISTS vehicle_assets (
 vehicle_id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
 make_model VARCHAR(120) DEFAULT NULL,
 production_year SMALLINT UNSIGNED DEFAULT NULL,
 fuel_type VARCHAR(40) DEFAULT NULL,
 ownership VARCHAR(80) DEFAULT NULL,
 owner_name VARCHAR(120) DEFAULT NULL,
 color VARCHAR(60) DEFAULT NULL,
 transmission VARCHAR(60) DEFAULT NULL,
 seats SMALLINT UNSIGNED DEFAULT NULL,
 vin VARCHAR(60) DEFAULT NULL,
 engine_number VARCHAR(60) DEFAULT NULL,
 insurance_provider VARCHAR(120) DEFAULT NULL,
 insurance_policy VARCHAR(100) DEFAULT NULL,
 insurance_expiry DATE DEFAULT NULL,
 tax_expiry DATE DEFAULT NULL,
 registration_expiry DATE DEFAULT NULL,
 tank_capacity_l DECIMAL(10,2) DEFAULT NULL,
 notes TEXT DEFAULT NULL,
 photo_mime VARCHAR(20) DEFAULT NULL,
 photo_updated_at DATETIME(3) DEFAULT NULL,
 updated_at DATETIME(3) NOT NULL,
 CONSTRAINT fk_vehicle_asset_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
